export function landPath(points) {
  return (
    points
      .map(
        ([lon, lat], index) =>
          `${index === 0 ? "M" : "L"}${(lon + 180).toFixed(1)} ${(90 - lat).toFixed(1)}`
      )
      .join(" ") + " Z"
  );
}

